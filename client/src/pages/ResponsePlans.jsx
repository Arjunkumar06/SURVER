import React, { useState, useEffect } from 'react';
import { 
  ClipboardList, 
  Send, 
  CheckCircle2, 
  Clock, 
  AlertTriangle, 
  ArrowRight, 
  Layers, 
  ShieldCheck, 
  RefreshCw,
  PlusCircle,
  FileText,
  Check,
  ChevronRight,
  Sparkles,
  Globe
} from 'lucide-react';
import { fetchResponsePlans, updatePlanStatus } from '../services/api';

const WORKFLOW_STAGES = ['Approved', 'Deploying', 'In Progress', 'Completed'];

const NEXT_STATUS_MAP = {
  'Approved': 'Deploying',
  'Deploying': 'In Progress',
  'In Progress': 'Completed',
  'Completed': null
};

export default function ResponsePlans() {
  const [plans, setPlans] = useState([]);
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [selectedPlan, setSelectedPlan] = useState(null);
  const [actionMessage, setActionMessage] = useState(null);
  const [updatingStatus, setUpdatingStatus] = useState(false);

  const loadPlans = async (isManualRefresh = false) => {
    if (isManualRefresh) setRefreshing(true);
    else setLoading(true);
    setActionMessage(null);

    try {
      const data = await fetchResponsePlans();
      setPlans(data);
      if (data.length > 0) {
        if (!selectedPlan) {
          setSelectedPlan(data[0]);
        } else {
          // Update selectedPlan with latest version from data
          const updated = data.find(p => p.id === selectedPlan.id || p._id === selectedPlan._id);
          if (updated) setSelectedPlan(updated);
        }
      }
      if (isManualRefresh) {
        setActionMessage({ type: 'success', text: `Successfully refreshed ${data.length} response plans from database.` });
        setTimeout(() => setActionMessage(null), 3000);
      }
    } catch (err) {
      console.error('Failed to load response plans:', err);
      setActionMessage({ type: 'error', text: 'Failed to fetch response plans. Check server connection.' });
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  };

  useEffect(() => {
    loadPlans();
    const interval = setInterval(() => loadPlans(false), 5000);
    return () => clearInterval(interval);
  }, []);

  const handleAdvanceWorkflow = async (plan, targetStatus) => {
    const planId = plan.id || plan._id;
    setUpdatingStatus(true);
    setActionMessage(null);

    try {
      const updated = await updatePlanStatus(planId, targetStatus);
      const newStatus = updated.status || targetStatus;

      setPlans(prevPlans =>
        prevPlans.map(p => (p.id === planId || p._id === planId ? { ...p, status: newStatus, workflowState: newStatus } : p))
      );

      if (selectedPlan && (selectedPlan.id === planId || selectedPlan._id === planId)) {
        setSelectedPlan({ ...selectedPlan, status: newStatus, workflowState: newStatus });
      }

      setActionMessage({
        type: 'success',
        text: `Plan ${plan.id || plan.zoneCode} successfully advanced to "${newStatus}".`
      });
      setTimeout(() => setActionMessage(null), 3500);
    } catch (err) {
      console.error('Status update failed:', err);
      setActionMessage({
        type: 'error',
        text: err.message || 'Failed to update workflow state.'
      });
    } finally {
      setUpdatingStatus(false);
    }
  };

  return (
    <div className="p-4 sm:p-6 space-y-6 max-w-7xl mx-auto">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <div className="flex items-center space-x-2">
            <h1 className="text-lg sm:text-xl font-mono font-extrabold text-slate-900 tracking-wider uppercase">
              Emergency Response Orchestration Pipeline
            </h1>
            <span className="px-2 py-0.5 text-[10px] font-mono font-bold bg-cyan-100 text-cyan-800 border border-cyan-300 rounded">
              State Machine v1.0
            </span>
          </div>
          <p className="text-xs text-slate-600 font-mono mt-0.5">
            Sequential multi-stage dispatch manifests generated by SURVER optimization algorithms
          </p>
        </div>

        {/* Refresh Plans Button */}
        <button
          onClick={() => loadPlans(true)}
          disabled={refreshing || loading}
          className="px-4 py-2 bg-white hover:bg-slate-100 disabled:opacity-50 text-slate-900 rounded-xl text-xs font-mono font-bold flex items-center space-x-2 border border-slate-300 transition shadow-sm shrink-0"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${refreshing ? 'animate-spin text-cyan-600' : ''}`} />
          <span>{refreshing ? 'Fetching Plans...' : 'Refresh Plans'}</span>
        </button>
      </div>

      {/* Action Notification Banner */}
      {actionMessage && (
        <div className={`p-3.5 rounded-2xl text-xs font-mono flex items-center space-x-2 backdrop-blur-xl transition shadow-sm ${
          actionMessage.type === 'success'
            ? 'bg-emerald-50 border border-emerald-300 text-emerald-800'
            : 'bg-rose-50 border border-rose-300 text-rose-800'
        }`}>
          {actionMessage.type === 'success' ? <CheckCircle2 className="w-4 h-4 text-emerald-600" /> : <AlertTriangle className="w-4 h-4 text-rose-600" />}
          <span>{actionMessage.text}</span>
        </div>
      )}

      {/* Main Grid: Plan List (Left) and Detail Manifest (Right) */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left Column: Plan Cards (5 cols) */}
        <div className="lg:col-span-5 space-y-3">
          <h2 className="text-xs font-mono font-bold uppercase tracking-wider text-slate-900">
            Active Orchestration Plans ({plans.length})
          </h2>

          <div className="space-y-2.5 max-h-[600px] overflow-y-auto pr-1 font-mono">
            {plans.map((plan) => {
              const isSelected = selectedPlan?.id === plan.id || selectedPlan?._id === plan._id;
              const currentStatus = plan.status || 'Approved';

              return (
                <div
                  key={plan.id || plan._id}
                  onClick={() => setSelectedPlan(plan)}
                  className={`p-4 rounded-2xl transition cursor-pointer space-y-2.5 ${
                    isSelected
                      ? 'bg-white border-2 border-cyan-500 shadow-md ring-1 ring-cyan-200'
                      : 'bg-white border border-slate-200 hover:border-slate-300 shadow-sm'
                  }`}
                >
                  <div className="flex items-center justify-between">
                    <div className="flex items-center space-x-2">
                      <span className="text-xs font-extrabold text-cyan-800 bg-cyan-50 px-2.5 py-0.5 rounded-lg border border-cyan-200 shadow-sm">
                        {plan.id || 'RP-1024'}
                      </span>
                      <span className="text-xs font-bold text-slate-900 uppercase tracking-wide">
                        {plan.zoneCode || 'ZONE'}
                      </span>
                      <span className="text-[10px] text-slate-500">
                        ({plan.country || 'Global'})
                      </span>
                    </div>

                    <span className={`px-2.5 py-0.5 text-[10px] font-bold rounded-full ${
                      currentStatus === 'Completed' ? 'bg-emerald-100 text-emerald-800 border border-emerald-300' :
                      currentStatus === 'In Progress' ? 'bg-purple-100 text-purple-800 border border-purple-300 animate-pulse' :
                      currentStatus === 'Deploying' ? 'bg-cyan-100 text-cyan-800 border border-cyan-300 animate-pulse' :
                      'bg-slate-100 text-slate-700 border border-slate-300'
                    }`}>
                      ● {currentStatus}
                    </span>
                  </div>

                  <div>
                    <h3 className="text-sm font-bold text-slate-900">{plan.disasterName || 'Emergency Response'}</h3>
                    <div className="flex items-center space-x-3 text-xs text-slate-500 mt-1 font-mono">
                      <span>Type: <strong className="text-slate-900">{plan.disasterType || 'Hazard'}</strong></span>
                      <span>Priority: <strong className="text-rose-600 font-bold">{plan.priorityScore}/100</strong></span>
                      <span>Coverage: <strong className="text-emerald-700 font-bold">{plan.coverage || 85}%</strong></span>
                    </div>
                  </div>
                </div>
              );
            })}
          </div>
        </div>

        {/* Right Column: Selected Plan Deep Manifest & Interactive State Machine (7 cols) */}
        <div className="lg:col-span-7">
          {selectedPlan ? (
            <div className="bg-white rounded-2xl p-6 space-y-6 shadow-sm relative border border-slate-200">
              {/* Header */}
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-slate-100 pb-4 font-mono">
                <div>
                  <div className="flex items-center space-x-2">
                    <span className="text-xs font-extrabold text-cyan-800 bg-cyan-50 px-3 py-1 rounded-xl border border-cyan-200">
                      {selectedPlan.id || 'RP-1024'}
                    </span>
                    <h2 className="text-base font-bold text-slate-900">
                      {selectedPlan.disasterName}
                    </h2>
                  </div>
                  <p className="text-xs text-slate-500 mt-1">
                    Target Sector: <strong className="text-cyan-700 font-bold">{selectedPlan.zoneCode}</strong> | Country: <strong className="text-slate-900">{selectedPlan.country || 'Global'}</strong> | Type: <strong className="text-slate-900">{selectedPlan.disasterType}</strong>
                  </p>
                </div>

                <div className="flex items-center space-x-2">
                  <span className="text-xs text-slate-500 font-mono">Priority Score:</span>
                  <span className="px-3 py-1 bg-cyan-50 text-cyan-800 font-mono font-extrabold text-xs rounded-xl border border-cyan-200">
                    {selectedPlan.priorityScore}/100
                  </span>
                </div>
              </div>

              {/* WORKFLOW EXECUTION PIPELINE & STATE MACHINE VISUALIZER */}
              <div className="p-4 bg-slate-50 border border-slate-200 rounded-2xl space-y-4 shadow-inner font-mono">
                <div className="flex items-center justify-between">
                  <span className="text-xs font-bold text-slate-900 uppercase tracking-wider flex items-center space-x-1.5">
                    <Clock className="w-3.5 h-3.5 text-cyan-600" />
                    <span>Workflow Execution State Machine</span>
                  </span>
                  <span className="text-xs font-bold text-cyan-700">
                    Current Stage: <span className="text-slate-900 uppercase font-bold">{selectedPlan.status || 'Approved'}</span>
                  </span>
                </div>

                {/* Visual Step Progress Bar */}
                <div className="grid grid-cols-4 gap-2">
                  {WORKFLOW_STAGES.map((stage, idx) => {
                    const currentIdx = WORKFLOW_STAGES.indexOf(selectedPlan.status || 'Approved');
                    const isCompleted = idx < currentIdx;
                    const isActive = idx === currentIdx;

                    return (
                      <div
                        key={stage}
                        className={`p-2.5 rounded-xl border text-center transition flex flex-col items-center justify-center space-y-1 ${
                          isActive
                            ? 'bg-slate-900 text-white border-slate-900 shadow-md'
                            : isCompleted
                            ? 'bg-emerald-100 text-emerald-800 border-emerald-300'
                            : 'bg-white text-slate-500 border-slate-200'
                        }`}
                      >
                        <div className="flex items-center space-x-1">
                          {isCompleted ? (
                            <Check className="w-3.5 h-3.5 text-emerald-600" />
                          ) : isActive ? (
                            <span className="w-2 h-2 rounded-full bg-cyan-400 animate-ping"></span>
                          ) : (
                            <span className="w-2 h-2 rounded-full bg-slate-300"></span>
                          )}
                          <span className="text-[11px] font-bold">
                            {stage}
                          </span>
                        </div>
                        <span className="text-[9px] uppercase font-mono tracking-wider font-semibold">
                          {isActive ? 'ACTIVE' : isCompleted ? 'COMPLETED' : 'PENDING'}
                        </span>
                      </div>
                    );
                  })}
                </div>

                {/* State Machine Transition Action Control */}
                <div className="flex items-center justify-between pt-2 border-t border-slate-200">
                  <span className="text-xs text-slate-500">
                    Next Stage: <strong className="text-cyan-700">{NEXT_STATUS_MAP[selectedPlan.status || 'Approved'] || 'Pipeline Completed'}</strong>
                  </span>

                  {NEXT_STATUS_MAP[selectedPlan.status || 'Approved'] ? (
                    <button
                      onClick={() => handleAdvanceWorkflow(selectedPlan, NEXT_STATUS_MAP[selectedPlan.status || 'Approved'])}
                      disabled={updatingStatus}
                      className="px-5 py-2 bg-cyan-600 hover:bg-cyan-700 text-white rounded-xl text-xs font-mono font-extrabold flex items-center space-x-1.5 transition shadow-sm"
                    >
                      {updatingStatus ? (
                        <>
                          <span className="w-3.5 h-3.5 border-2 border-white/30 border-t-white rounded-full animate-spin"></span>
                          <span>Advancing Workflow...</span>
                        </>
                      ) : (
                        <>
                          <span>Advance to {NEXT_STATUS_MAP[selectedPlan.status || 'Approved']}</span>
                          <ChevronRight className="w-4 h-4" />
                        </>
                      )}
                    </button>
                  ) : (
                    <span className="px-3 py-1.5 bg-emerald-100 text-emerald-800 border border-emerald-300 rounded-xl text-xs font-mono font-bold flex items-center space-x-1 shadow-sm">
                      <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />
                      <span>Response Plan Fully Executed</span>
                    </span>
                  )}
                </div>
              </div>

              {/* Resource Shortages Alert if any */}
              {selectedPlan.shortages && selectedPlan.shortages.length > 0 && (
                <div className="p-4 bg-amber-50 border border-amber-300 rounded-2xl space-y-2 text-xs shadow-sm font-mono">
                  <div className="flex items-center space-x-2 text-amber-800 font-bold uppercase tracking-wider">
                    <AlertTriangle className="w-4 h-4 text-amber-600" />
                    <span>Resource Shortage Deficit Flagged</span>
                  </div>
                  {selectedPlan.shortages.map((s, idx) => (
                    <div key={idx} className="flex justify-between bg-white p-2.5 rounded-xl border border-amber-200 text-slate-900">
                      <span><strong>{s.label || s.resourceType}:</strong> Required {s.required} {s.unit}, Allocated {s.availableAllocated} {s.unit}</span>
                      <span className="text-rose-600 font-bold">Deficit: -{s.shortage} {s.unit}</span>
                    </div>
                  ))}
                </div>
              )}

              {/* Dispatch Manifest Table */}
              <div className="space-y-3">
                <h3 className="text-xs font-mono font-bold uppercase tracking-wider text-slate-900">
                  Allocated Dispatch Manifest ({selectedPlan.allocations?.length || 0} Assets):
                </h3>

                <div className="space-y-2 max-h-56 overflow-y-auto pr-1 font-mono">
                  {selectedPlan.allocations?.map((item, idx) => (
                    <div
                      key={idx}
                      className="p-3 bg-slate-50 border border-slate-200 rounded-xl flex items-center justify-between text-xs hover:bg-slate-100 transition"
                    >
                      <div className="space-y-0.5">
                        <div className="font-bold text-slate-900 flex items-center space-x-1.5">
                          <span className="text-cyan-700 font-bold">{item.quantity} {item.unit}</span>
                          <span className="text-slate-800">({item.label || item.resourceType})</span>
                        </div>
                        <div className="text-[11px] text-slate-500">
                          Origin Depot: <span className="text-slate-900 font-medium">{item.sourceFacility}</span>
                        </div>
                      </div>

                      <div className="text-right shrink-0 flex items-center space-x-1 text-cyan-700 font-mono text-[11px]">
                        <ArrowRight className="w-3 h-3 text-slate-400" />
                        <span className="font-bold">{selectedPlan.zoneCode}</span>
                      </div>
                    </div>
                  ))}
                </div>
              </div>

              {/* Explainable Decision Summary */}
              {selectedPlan.explanation && (
                <div className="p-3.5 bg-slate-50 border border-slate-200 rounded-2xl space-y-1.5 text-xs text-slate-900 font-mono">
                  <span className="font-bold text-cyan-700 text-[11px] uppercase tracking-wider block">
                    AI Decision Summary:
                  </span>
                  <p className="leading-relaxed text-slate-700">{selectedPlan.explanation.summary}</p>
                </div>
              )}
            </div>
          ) : (
            <div className="h-96 rounded-2xl bg-white border border-dashed border-slate-300 flex items-center justify-center text-slate-500 text-xs font-mono">
              Select a response plan from the left to inspect manifest
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
